        <div class="tx8n3rich">
            <p>Plans for the future remain modest. Maintain the equipment. Keep the menu honest. Listen when the neighborhood changes. Add a new seating option only if the current layout feels tight. Introduce a seasonal item when the ingredients are at their best, not because a calendar says so.</p>
            <p>The café is not trying to become a landmark or a trend. It aims to remain a dependable part of daily routes. That requires attention to small details more than bold gestures. The people who work here and the people who visit have both contributed to keeping that focus clear.</p>
