        <h2>Milestones Along the Way</h2>
        <div class="tx8n3rich">
            <h3>Year One</h3>
            <p>The doors opened in late spring. The first summer brought long light evenings and a steady stream of walkers. By autumn the morning rush had formed its own pattern. A small chalkboard listed the bean of the week. That board is still used today, though the handwriting has changed hands many times.</p>
            <h3>Year Three</h3>
            <p>A second grinder was added. The seating layout was adjusted after listening to feedback about drafty corners. A local potter began supplying a few of the cups. The café hosted its first quiet reading evening — no formal program, just dimmed lights and a longer closing time for those who wanted to stay.</p>
            <h3>Year Five and Beyond</h3>
            <p>The neighborhood shifted around the café, but the interior remained familiar. New faces arrived; long-time regulars stayed. The team grew by one or two people at a time, always with training that emphasized the same values: clean equipment, measured pours, and room for conversation when the line allows. The original vision — a calm, well-run stop for the people nearby — has held without needing reinvention.</p>
            <p>Today Vimoronow continues under the same principles. The owners still work shifts. The suppliers are chosen for reliability as much as flavor. The space is maintained rather than redesigned every season. Visitors who return after years often say it feels the same, only more settled.</p>
        </div>
    </section>

